import type { IsoDate } from '../dates.ts';
import type { ComplianceScope, DocumentType, Nation, SubjectFacts } from '../types.ts';

/**
 * SEED RULE SET - NOT LEGAL ADVICE.
 *
 * These rules were written from general knowledge of UK lettings law as a
 * starting point. Every rule, period and legal reference must be reviewed by a
 * lettings solicitor before the product is sold to other agencies. Local
 * schemes (selective and additional licensing) are not included: add them per
 * council as rules with a `council` condition when that feature is built.
 *
 * Rules are data. To reflect a change in the law, add a rule with
 * `effectiveFrom` (and close the old one with `effectiveTo`); do not edit history.
 */

export type Recurrence =
  /** Renew every N months from the date last completed (certificates, registrations). */
  | { kind: 'interval'; months: number }
  /** Do once; never expires (for example, alarms installed to the required standard). */
  | { kind: 'once' }
  /** Do once, within N days of an event on the tenancy. */
  | { kind: 'deadline'; days: number; workingDays?: boolean; from: 'tenancy_start' | 'deposit_received' };

export interface ComplianceRule {
  id: string;
  nations: readonly Nation[];
  scope: ComplianceScope;
  title: string;
  description: string;
  recurrence: Recurrence;
  /** The rule applies only when every listed fact is true for the subject. */
  when?: SubjectFacts;
  evidence: DocumentType | null;
  /** `statutory` counts towards the compliance score; `best_practice` is advisory. */
  severity: 'statutory' | 'best_practice';
  /** `upcoming` rules are shown as a readiness tracker and not scored. */
  status: 'in_force' | 'upcoming';
  legalBasis: string;
  effectiveFrom?: IsoDate;
  effectiveTo?: IsoDate;
}

